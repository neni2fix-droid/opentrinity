// Package routingconfig generates LiteLLM YAML from validated local state.
// It never writes secret values: only os.environ references.
package routingconfig

import (
	"fmt"
	"net"
	"net/url"
	"strings"

	"github.com/nenifix/opentrinity/internal/config"
	"github.com/nenifix/opentrinity/internal/database"
)

// Snapshot is the minimal validated state needed for config generation.
type Snapshot struct {
	Providers   []database.Provider
	Credentials []database.Credential
	Models      []database.Model
	Deployments []database.Deployment
}

type selectedSlot struct {
	Slot       string
	Group      string
	ModelID    string
	APIBase    string
	SecretRef  string
}

// Groups returns the client-visible model groups in configured order.
func Groups() []string {
	return []string{config.Alias, config.Alias + "-b", config.Alias + "-c"}
}

// Validate checks deployment continuity, references and outbound URL safety.
func (s Snapshot) Validate() ([]selectedSlot, error) {
	byProvider := map[int64]database.Provider{}
	for _, p := range s.Providers {
		if p.Enabled {
			byProvider[p.ID] = p
		}
	}
	credByProvider := map[int64]database.Credential{}
	for _, c := range s.Credentials {
		if c.Enabled {
			if _, exists := credByProvider[c.ProviderID]; !exists {
				credByProvider[c.ProviderID] = c
			}
		}
	}
	modelByID := map[int64]database.Model{}
	for _, m := range s.Models {
		if m.Enabled {
			modelByID[m.ID] = m
		}
	}
	depBySlot := map[string]database.Deployment{}
	for _, d := range s.Deployments {
		depBySlot[d.Slot] = d
	}

	var selected []selectedSlot
	var seenGap bool
	for i, slotName := range []string{"A", "B", "C"} {
		d, ok := depBySlot[slotName]
		if !ok || !d.Enabled {
			seenGap = true
			continue
		}
		if seenGap {
			return nil, fmt.Errorf("deployment slot %s is enabled after a disabled slot; order must be contiguous from A", slotName)
		}
		m, ok := modelByID[d.ModelID]
		if !ok {
			return nil, fmt.Errorf("deployment slot %s references a missing or disabled model", slotName)
		}
		p, ok := byProvider[m.ProviderID]
		if !ok {
			return nil, fmt.Errorf("model %q references a missing or disabled provider", m.ModelID)
		}
		c, ok := credByProvider[p.ID]
		if !ok {
			return nil, fmt.Errorf("provider %q has no enabled credential", p.Name)
		}
		if err := ValidateAPIBase(p.APIBase); err != nil {
			return nil, fmt.Errorf("provider %q API base: %w", p.Name, err)
		}
		selected = append(selected, selectedSlot{
			Slot:      slotName,
			Group:     Groups()[i],
			ModelID:   m.ModelID,
			APIBase:   p.APIBase,
			SecretRef: c.SecretRef,
		})
	}
	if len(selected) == 0 {
		return nil, fmt.Errorf("at least one enabled deployment slot is required")
	}
	return selected, nil
}

// ValidateAPIBase permits loopback HTTP and public HTTPS only. It performs no
// network fetch and rejects credentials, query strings and fragments.
func ValidateAPIBase(raw string) error {
	u, err := url.Parse(raw)
	if err != nil {
		return err
	}
	if u.User != nil || u.RawQuery != "" || u.Fragment != "" {
		return fmt.Errorf("userinfo, query and fragment are not allowed")
	}
	host := u.Hostname()
	if host == "" {
		return fmt.Errorf("missing host")
	}
	if strings.Contains(host, "..") || strings.ContainsAny(host, " \t\r\n") {
		return fmt.Errorf("invalid host")
	}
	isLoopback := false
	if ip := net.ParseIP(host); ip != nil {
		isLoopback = ip.IsLoopback()
		if ip.IsUnspecified() || ip.IsMulticast() {
			return fmt.Errorf("unsupported IP destination")
		}
	} else if strings.EqualFold(host, "localhost") {
		isLoopback = true
	}
	if u.Scheme == "http" && !isLoopback {
		return fmt.Errorf("plain HTTP is only allowed on loopback")
	}
	if u.Scheme != "http" && u.Scheme != "https" {
		return fmt.Errorf("unsupported scheme %q", u.Scheme)
	}
	return nil
}

// Generate produces deterministic LiteLLM YAML with placeholder-only secrets.
func Generate(s Snapshot) (string, error) {
	slots, err := s.Validate()
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("# Generated by OPENTRINITY. Secrets are environment references only.\n")
	b.WriteString("model_list:\n")
	for _, slot := range slots {
		b.WriteString(fmt.Sprintf("  - model_name: %s\n", slot.Group))
		b.WriteString("    litellm_params:\n")
		b.WriteString(fmt.Sprintf("      model: %s\n", yamlQuote("openai/"+slot.ModelID)))
		b.WriteString(fmt.Sprintf("      api_base: %s\n", yamlQuote(slot.APIBase)))
		b.WriteString(fmt.Sprintf("      api_key: %s\n", yamlQuote("os.environ/"+slot.SecretRef)))
	}
	b.WriteString("\nrouter_settings:\n")
	b.WriteString("  num_retries: 0\n")
	b.WriteString("  allowed_fails: 0\n")
	b.WriteString("  disable_cooldowns: true\n")
	b.WriteString("  cooldown_time: 0\n")
	// SPEC.md: per-attempt total timeout is 45 seconds.
	b.WriteString("  timeout: 45\n")
	b.WriteString("  fallbacks:\n")
	for i := 0; i < len(slots)-1; i++ {
		b.WriteString(fmt.Sprintf("    - %s: [%s]\n", slots[i].Group, slots[i+1].Group))
	}
	b.WriteString("\nlitellm_settings:\n")
	b.WriteString("  drop_params: true\n")
	b.WriteString("  telemetry: false\n")
	b.WriteString("  success_callback: []\n")
	b.WriteString("  failure_callback: []\n")
	b.WriteString("  set_verbose: false\n")
	b.WriteString("\ngeneral_settings:\n")
	b.WriteString("  master_key: os.environ/OT_LITELLM_KEY\n")
	return b.String(), nil
}

func yamlQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}
